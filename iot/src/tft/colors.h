#ifndef COLORS_H
#define COLORS_H

// ==========================================
// BẢNG MÀU HỆ THỐNG (16-bit 565)
// ==========================================
#define COLOR_BG 0x0000      // Đen sâu
#define COLOR_CARD 0x18E3    // Xám xanh đậm (Nền thẻ)
#define COLOR_TEXT 0xFFFF    // Trắng
#define COLOR_SUBTEXT 0xAD55 // Xám nhạt
#define COLOR_ACCENT 0x07FF  // Xanh Cyan Neon (Highlight)
#define COLOR_PRICE 0xFBE0   // Vàng cam rực (Giá tiền)
#define COLOR_STT_BG 0x2104  // Đỏ đậm cho khung STT
#define COLOR_TEMP 0xFBE0    // Cam rực (Nhiệt độ)
#define COLOR_HUMID 0x24FF   // Xanh dương (Độ ẩm)
#define COLOR_UV 0xFD00      // Vàng cam (UV)
#define COLOR_AQI_G 0x07E0   // Xanh lá (AQI Tốt)
#define COLOR_AQI_Y 0xFFE0   // Vàng (AQI Trung bình)
#define COLOR_SUCCESS 0x07E0 // Xanh lá (Thành công)
#define COLOR_ERROR 0xF800   // Đỏ rực rỡ (Lỗi)

#endif